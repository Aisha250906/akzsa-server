import java.text.Normalizer

/**
 * Built-in Hinglish dictionary used when the Hindi speech engine answers in Devanagari.
 *
 *  1. English words that Hindi engines write in Devanagari ("इनवॉइस") go back to normal English spelling ("invoice").
 *  2. Very common Hindi words get the spelling people actually type in Hinglish ("नहीं" -> "nahi"), which a letter-by-letter
 *     converter cannot always guess.
 *
 * Lookup ignores nukta dots and candrabindu/anusvara differences, so "फ़ोन"/"फोन" and "हाँ"/"हां" both match.
 * Anything not in this list still goes through [HinglishTransliterator]'s rule-based conversion.
 * Format of the data blocks: `variant1,variant2=Roman` per line; `#` starts a comment.
 */
object HinglishDictionary {
    fun lookup(word: String): String? = table[key(word)]

    val size: Int get() = table.size

    internal fun key(word: String): String =
        Normalizer.normalize(word, Normalizer.Form.NFC).replace("\u093C", "").replace('\u0901', '\u0902')

    private val table: Map<String, String> by lazy {
        val map = HashMap<String, String>(2048)
        for (data in listOf(LOANWORDS, LOANWORDS_2, HINDI, HINDI_2, NUMBERS_AND_TIME)) parseInto(map, data)
        map
    }

    private fun parseInto(map: MutableMap<String, String>, data: String) {
        for (line in data.lineSequence()) {
            val trimmed = line.trim()
            if (trimmed.isEmpty() || trimmed.startsWith("#")) continue
            val eq = trimmed.indexOf('=')
            if (eq <= 0 || eq == trimmed.length - 1) continue
            val roman = trimmed.substring(eq + 1).trim()
            for (variant in trimmed.substring(0, eq).split(',')) {
                val v = variant.trim()
                if (v.isNotEmpty()) map[key(v)] = roman
            }
        }
    }

